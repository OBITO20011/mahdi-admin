import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {canonicalLf,sha256} from './maintenance-db-contract.mjs';

const root=new URL('../../',import.meta.url);
const check=process.argv[2]==='--check';
assert.ok(process.argv.length===2||process.argv.length===3&&check,'ONLY_CHECK_OPTION');
const sources=['prototype223.sql','lifecycle223.sql','private-writers223.sql'];
const sections=await Promise.all(sources.map(async name=>{
 const source=canonicalLf(await readFile(new URL('docs/design/off-quantity-counter223/'+name,root),'utf8'));
 const matches=source.match(/^[\s\S]*?^BEGIN;\n([\s\S]+)\nCOMMIT;\s*$/mu);
 assert.ok(matches,'EXACT_QUANTITY223_TRANSACTION:'+name);
 assert.equal((source.match(/^(?:BEGIN|COMMIT);$/gmu)??[]).length,2,'NESTED_QUANTITY223_TRANSACTION:'+name);
 // One transactional migration and one schema-cache signal at commit.
 return matches[1].replace(/^NOTIFY pgrst,'reload schema';\n?/mu,'').trimEnd();
}));
const migration='-- Generated by build-optional-quantity223-migration.mjs.\n'+
 '-- Optional quantity in OFF only. Accounting migration 221 remains reserved.\nBEGIN;\n'+
 sections.join('\n\n')+"\nNOTIFY pgrst,'reload schema';\nCOMMIT;\n";
const target=new URL('supabase/migrations/223_optional_sales_quantity.sql',root);
if(check)assert.equal(canonicalLf(await readFile(target,'utf8')),migration,'QUANTITY223_MIGRATION_SOURCE_DRIFT');
else await writeFile(target,migration,{flag:'wx'});
console.log(JSON.stringify({ok:true,sha256:sha256(migration),checkOnly:check}));
