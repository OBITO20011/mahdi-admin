// Inventory/assessment only. Never run,disable,unschedule or dispatch a job.
export const businessCronJobs=Object.freeze([
 {name:'expire-stale-new-website-orders',migration:'091',calls:'public.expire_stale_new_website_orders(100)',effect:'outbox'},
 {name:'cleanup-guest-order-gateway-requests',migration:'092',calls:'public.cleanup_guest_order_gateway_requests(500)',effect:'database-only'},
 {name:'scan-core-business-alerts',migration:'097',calls:'public.scan_core_business_alerts(NOW(), 100)',effect:'outbox'},
 {name:'scan-business-summaries',migration:'098',calls:'public.scan_business_summaries(NOW())',effect:'outbox'},
 {name:'run-advanced-monitoring',migration:'099',calls:'public.run_advanced_monitoring_checks()',effect:'outbox'},
]);
export const cronInventorySql=`BEGIN READ ONLY;
 SELECT COALESCE(jsonb_agg(jsonb_build_object('name',jobname,'schedule',schedule,'command',command,'active',active)
 ORDER BY jobname),'[]'::jsonb) FROM cron.job
 WHERE jobname IN (${businessCronJobs.map(j=>"'"+j.name+"'").join(',')});ROLLBACK;`;
export function assessBuildCron(rows,{migrationCeiling=138}={}){
 if(rows.length!==businessCronJobs.length||new Set(rows.map(r=>r.name)).size!==rows.length)
  throw new Error('EXPECTED_MIGRATION_CRON_INVENTORY_REQUIRED');
 const jobs=businessCronJobs.map(rule=>{
  const row=rows.find(r=>r.name===rule.name);
  if(!row||row.command.replace(/\s/gu,'').toLowerCase()!==('SELECT '+rule.calls+';').replace(/\s/gu,'').toLowerCase())
   throw new Error('CRON_COMMAND_CHANGED:'+rule.name);
  return {...row,migration:rule.migration,effect:rule.effect,directHttp:false,
   externalDeliveryRequiresConsumer:rule.effect==='outbox'};
 });
 return {jobs,requiresOwnerReview:false,ownerApprovedTemporaryHold:true,
  proposedTemporaryDisabledJobs:jobs.filter(j=>j.effect==='outbox').map(j=>j.name),
  currentTransport:'Only DB/outbox writes;no Edge deployment or consumer configuration is part of this build',
  orderInsertRisk:{migration:migrationCeiling>=139?'139':'033',trigger:'trg_notify_new_website_order_push',
   event:'AFTER INSERT public.orders WHERE source=website AND status=new',
   secret:'Automatically generated by033;no value read by this audit',
   endpointProject:migrationCeiling>=139?null:'acjtabdqqnpwhdvbvnyw',automaticHttp:true,
   ...(migrationCeiling>=139?{endpointSetting:'Vault:order_push_webhook_url',unsetSetting:'no request;no default URL'}:{}),
   proposedAction:'Owner-approved temporary trigger disable before any website-order probe;not a cron job'},
  implementedDisable:false,externalRequestExecuted:false};
}
